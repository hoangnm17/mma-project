import { spawnSync } from "node:child_process";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import path from "node:path";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";

const root = fileURLToPath(new URL("../../", import.meta.url));
const backend = path.join(root, "backend");
process.env.MONGO_DATABASE = "StayFlow_" + Date.now() + "Test";
process.env.JWT_SECRET = "ui-test-only-secret-with-at-least-32-characters";
process.env.DEMO_SEED_PASSWORD = "UITestOnly!2026";
process.env.OPENAI_API_KEY = "";
process.env.GEMINI_API_KEY = "";
process.env.AI_PROVIDER = "";
process.env.PUSH_ENABLED = "false";
process.env.WEB_DIST = path.join(root, "artifacts", "ui-web");
process.env.CORS_ORIGINS = "http://127.0.0.1:4011";
const runtime = process.env.CODEX_NODE_MODULES || path.join(process.env.LOCALAPPDATA || "", "..", "..", ".cache", "codex-runtimes", "codex-primary-runtime", "dependencies", "node", "node_modules");
const require = createRequire(path.join(runtime, "package.json"));
const { chromium } = require("playwright");
const { database, closeDatabase } = await import("../src/db.js");
let server, browser;
const screenshots = path.join(root, "artifacts", "ui-regression");
await mkdir(screenshots, { recursive: true });
const errors = [];
try {
  for (const script of ["migrate.js", "seed.js"]) {
    const run = spawnSync(process.execPath, ["scripts/" + script], { cwd: backend, env: process.env, stdio: "inherit", windowsHide: true });
    assert.equal(run.status, 0, script);
  }
  const { createApp } = await import("../src/app.js");
  server = createApp().listen(4011, "127.0.0.1");
  await new Promise(resolve => server.once("listening", resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  browser = await chromium.launch({ channel: "chrome", headless: true, args: ["--disable-dev-shm-usage"] });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1 });
  page.on("pageerror", error => errors.push(error.message));
  page.on("requestfailed", request => console.error("UI network:", request.url(), request.failure()?.errorText));
  page.on("console", message => { if (message.type() === "error") console.error("UI console:", message.text()); });
  await page.route("**/*", route => new URL(route.request().url()).hostname === "127.0.0.1" ? route.continue() : route.abort());
  await page.routeWebSocket("**/socket.io/**", socket => socket.close());
  const button = name => page.getByRole("button", { name: new RegExp(name.replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + "\\s*$") }).last();
  const field = name => page.getByLabel(name, { exact: true });
  const submit = async (label, action) => {
    const waiting = page.waitForResponse(response => response.request().method() === "POST" && response.url().endsWith("/api/actions/" + action));
    await button(label).click();
    const response = await waiting;
    const body = await response.json();
    assert.equal(response.status(), 200, JSON.stringify(body));
    return body;
  };
  const close = async () => { await button("Đóng").click(); };
  await page.goto(base, { waitUntil: "domcontentloaded" });
  await field("Tên đăng nhập").fill("admin");
  await field("Mật khẩu").fill(process.env.DEMO_SEED_PASSWORD);
  const loginResponse = page.waitForResponse(response => response.url().includes("/api/auth/login"), { timeout: 10000 });
  await button("Đăng nhập").click();
  const loginResult = await loginResponse;
  assert.equal(loginResult.status(), 200, await loginResult.text());
  await button("Thêm").waitFor();
  await page.getByText("Phòng trống", { exact: true }).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), "Dashboard overflows the mobile viewport");
  await page.screenshot({ path: path.join(screenshots, "dashboard.png") });
  await button("Đặt phòng").click();
  const availableResponse = page.waitForResponse(response => response.url().includes("/api/availability"));
  await button("Tạo đặt phòng").click();
  const available = await availableResponse;
  assert.equal(available.status(), 200);
  const availableRooms = await available.json();
  assert.ok(availableRooms.length > 0);
  await page.getByText("Phòng còn trống", { exact: true }).waitFor();
  await page.getByText(new RegExp(availableRooms[0].number + " ·")).first().waitFor();
  console.log("PASS booking form loads available rooms without end time");
  await close();
  await button("Phiếu thu và hoàn cọc").first().click();
  await field("Số tiền VND").waitFor();
  await field("Số tiền VND").fill("10000");
  await submit("Thu thêm cọc tiền mặt", "receipt");
  await field("Số tiền VND").fill("5000");
  await field("Lý do hoàn cọc").fill("Hoàn cọc kiểm thử");
  await submit("Hoàn số tiền đã nhập từ phiếu này", "receipt-return");
  assert.equal(errors.length, 0, errors.join("\n"));
  await page.screenshot({ path: path.join(screenshots, "booking-receipts.png") });
  await close();
  console.log("PASS booking receipts/refunds dialog retains session context");
  await button("Thêm").click();
  await button("Lưu trú").click();
  await button("Chi tiết").first().click();
  await page.getByText("Tạm tính", { exact: true }).waitFor();
  await button("Dịch vụ").click();
  await page.getByText("Thêm dịch vụ", { exact: true }).first().waitFor();
  await page.getByRole("button", { name: /Nước suối/ }).click();
  await field("Số lượng").fill("2");
  await submit("Thêm dịch vụ", "serviceItem");
  await button("Thu tiền").first().click();
  await field("Số tiền VND").first().waitFor();
  await button("Trả phòng").first().click();
  await button("Thu tiền & trả phòng").waitFor();
  assert.equal(errors.length, 0, errors.join("\n"));
  await page.screenshot({ path: path.join(screenshots, "stay-checkout.png") });
  await close();
  console.log("PASS stay details/services/receipt/checkout dialogs retain session context");
  await button("Phòng").click();
  await button("Nhận phòng trực tiếp").first().click();
  await field("Điện thoại khách hàng").fill("0989876543");
  await field("Họ tên khách").fill("Khách UI Test");
  await button("Xác nhận nhận phòng").click();
  await field("Điện thoại khách hàng").waitFor({ state: "hidden" });
  assert.equal(errors.length, 0, errors.join("\n"));
  console.log("PASS direct check-in completes through UI");
  await button("Thêm").click();
  await button("Lưu trú").click();
  await page.getByRole("button", { name: /Chi tiết\s*$/ }).first().click();
  await page.getByText("Tạm tính", { exact: true }).waitFor();
  const invoice = await submit("Thu tiền & trả phòng", "checkout");
  assert.ok(invoice.id && invoice.total > 0);
  await button("Thu tiền & trả phòng").waitFor({ state: "hidden" });
  const ctx = await database();
  assert.equal(await ctx.db.collection("Invoices").countDocuments({ id: invoice.id }), 1);
  assert.equal(errors.length, 0, errors.join("\n"));
  console.log("PASS checkout records payment and invoice through UI");
  await writeFile(path.join(screenshots, "results.json"), JSON.stringify({ passed: 5, errors, viewport: "390x844" }, null, 2));
} catch (error) {
  if (browser) for (const context of browser.contexts()) for (const page of context.pages()) {
    await page.screenshot({ path: path.join(screenshots, "failure.png") }).catch(() => {});
    await writeFile(path.join(screenshots, "failure.txt"), await page.locator("body").innerText().catch(() => ""));
  }
  throw error;
} finally {
  await browser?.close();
  if (server) await new Promise(resolve => server.close(resolve));
  const ctx = await database();
  assert.match(process.env.MONGO_DATABASE, /^StayFlow_\d+Test$/);
  await ctx.db.dropDatabase();
  await closeDatabase();
}
